package dev.htmeta.obfuscateguard.keeprules

import dev.htmeta.obfuscateguard.core.model.KeepRule

/**
 * Merges ObfuscateGuard-generated keep rules into an existing ProGuard config
 * without touching hand-written content. Generated rules live between marker
 * comments and are replaced atomically on re-export.
 */
object KeepRulesExporter {

    const val BEGIN_MARKER = "# == ObfuscateGuard generated keep rules (begin) =="
    const val END_MARKER = "# == ObfuscateGuard generated keep rules (end) =="

    fun renderBlock(rules: List<KeepRule>): String {
        val sb = StringBuilder()
        sb.appendLine(BEGIN_MARKER)
        sb.appendLine("# Do not edit between these markers — regenerated by ObfuscateGuard.")
        for (rule in rules.filter { it.accepted }.distinctBy { it.pattern }) {
            if (rule.reason.isNotBlank()) sb.appendLine("# ${rule.reason}")
            sb.appendLine(rule.toProGuardRule())
        }
        sb.append(END_MARKER)
        return sb.toString()
    }

    /**
     * Returns the new file content: replaces an existing generated block,
     * or appends one at the end while preserving all user content.
     */
    fun merge(existingContent: String, rules: List<KeepRule>): String {
        val block = renderBlock(rules)
        val beginIdx = existingContent.indexOf(BEGIN_MARKER)
        val endIdx = existingContent.indexOf(END_MARKER)

        return if (beginIdx >= 0 && endIdx > beginIdx) {
            existingContent.substring(0, beginIdx) +
                block +
                existingContent.substring(endIdx + END_MARKER.length)
        } else {
            val separator = when {
                existingContent.isBlank() -> ""
                existingContent.endsWith("\n\n") -> ""
                existingContent.endsWith("\n") -> "\n"
                else -> "\n\n"
            }
            existingContent + separator + block + "\n"
        }
    }
}
